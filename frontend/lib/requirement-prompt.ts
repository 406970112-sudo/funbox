export const REQUIREMENT_PROMPT_PLACEHOLDER = '【在这里填写具体需求，尽量描述：什么场景、什么操作、当前结果、期望结果】';

export const REQUIREMENT_PROMPT_TEMPLATE = `# 代码修改任务：先分析，确认后实施

## 本次需求

${REQUIREMENT_PROMPT_PLACEHOLDER}

**当前只需要 Markdown 方案，不要修改代码。先阅读现有实现并核实需求，待我明确确认实施后再修改。**

## 工作原则

### 1. 先确认需求，再选择实现

- 用自己的话复述目标、触发条件、预期结果和必须保留的行为，并整理为编号验收条目。
- 区分“我明确提出的要求”和“你提出的建议”，不要将建议自动纳入需求。
- 如果存在会影响业务行为、改动范围、数据或兼容性的歧义，先提出必要问题，不要擅自决定；可以继续开展不依赖这些答案的只读分析。
- 不影响上述事项的实现细节，优先沿用项目现有约定，无需反复询问。

### 2. 结论必须有依据

- 明确区分：**已确认事实、基于证据的推断、待确认事项**。
- 关于当前实现和调用链的关键结论，应提供文件路径、函数或组件名称，必要时附行号。
- 不要仅凭命名、注释、mock 或局部函数推断实际行为；检查实际引用、入口注册和相关配置。
- 无法访问代码、运行环境或外部系统时，明确说明限制，不要编造实现、调用链或验证结果。

### 3. 按相关性检查完整链路

- 从需求对应的实际入口，追踪到最终可观察结果，并检查会影响该结果的上下游。
- 输入、状态、分支、接口、回调、异步、页面生命周期、消息队列、缓存和持久化等，只检查真实存在且与本需求有关的部分，不机械扩展为全项目排查。
- 如果涉及共享函数、公共组件、接口或数据结构，检查相关调用方，确认是否会改变其他业务分支。
- 从代码确认的路径与实际运行验证的路径应分别说明。

### 4. 采用最小充分修改

- 每项拟议改动必须对应某条验收标准，或说明它为什么是完成需求所必需的配套修改。
- 优先复用现有结构和约定；“最小”指行为影响范围受控，不是单纯追求修改行数最少。
- 不顺手重构、统一格式、升级依赖、调整无关配置、优化无关性能或修复无关问题。
- 发现无关问题时单独记录，不纳入本次实施。
- 如果后续发现必须扩大已确认的行为、接口、数据或兼容性范围，先更新方案并获得确认。

### 5. 覆盖实际应用路径

- 改动必须作用于真实应用入口所经过的正式调用路径。
- 可以只修改底层函数，但必须证明真实入口会经过该函数，且修改能实现需求。
- 不能仅修改 mock、测试桩或孤立路径来制造“已完成”的结果。
- 验证正式调用路径不代表需要连接生产环境或操作生产数据。

### 6. 保护已有工作

- 实施前识别已有未提交改动，不回退、覆盖或混入与本需求无关的修改。
- 如果已有改动与本次修改重叠，先理解并保留其意图；无法兼容时说明具体冲突。

## 第一阶段：只读分析与方案

此阶段仅阅读、检索和分析，在对话中输出方案。不要编辑项目文件、安装依赖，或执行会改变工作区、环境和业务数据的操作。

请按以下结构输出，深度与需求复杂度匹配，避免重复描述。

### 1. 当前实现

- 需求理解与编号验收条目；未明确给出的验收条件标为“建议，待确认”。
- 当前行为、真实入口、关键实现位置和最终可观察结果。
- 当前行为与目标的差距，以及有证据支持的原因。
- 关键未知事项和需要回答的问题。

### 2. 完整影响链路

- 用“入口 → 处理层 → 状态或数据变化 → 最终结果”描述与需求相关的完整路径，标注关键文件和函数。
- 检查相关层之间的参数、返回值、错误和状态是否完整传递，关注包装层、适配层、默认值、fallback 和错误转换。
- 按实际相关性检查边界输入、业务分支、重复触发、去重、异步顺序、取消与重试、页面切换、缓存和持久化。
- 如果涉及共享能力，说明其他调用方及兼容性影响。
- 对无法确认的链路明确标注，不用猜测补齐。

### 3. 改造点

逐项说明：

| 改造点 | 对应验收条目 | 拟修改文件或符号 | 修改内容及必要性 |
| --- | ------ | -------- | -------- |

给出推荐方案和关键实施顺序。只有存在实质性取舍时，才补充备选方案及其差异。

### 4. 前后差异

按业务场景对比：

| 场景或输入 | 当前行为 | 目标行为 | 必须保持的行为 |
| ----- | ---- | ---- | ------- |

说明接口、错误语义、默认行为和数据兼容性是否变化；如需迁移，明确其必要性和影响。

### 5. 非改造范围

- 列出容易被本次改动波及、但应保持不变的模块和行为。
- 明确哪些相关问题本次不处理。
- 确认方案中没有无法关联需求或必要依赖的改动。

### 6. 风险和测试方案

- 列出具体风险、触发条件、潜在后果和验证方法，避免泛泛描述。
- 将验收条目与测试场景对应，明确测试入口和预期可观察结果。
- 根据实际行为和风险，选择正常、异常、边界、重复触发和不同业务分支等用例；不为凑分类添加无关测试。
- 涉及共享能力时，覆盖受影响调用方的兼容性回归。
- 验证最终结果及必要副作用，例如页面展示、接口响应、实际数据变化或任务结果，不能只验证中间函数返回值。
- 优先复用现有测试设施。可以替换外部依赖，但保留本次改动涉及的实际内部调用链。
- 列出计划执行的测试、静态检查和人工验证，以及当前无法验证的部分。

**输出方案后停止，等待我明确确认实施。方案中的修改和测试均应表述为“拟修改”“计划验证”，不要描述成已经完成。**

## 第二阶段：我确认后实施

1. 按已确认方案完成必要修改，保留已有无关改动。
2. 对缺陷修复，优先建立能复现原问题的回归用例；对新增行为，将验收条件落实为适当的测试。
3. 执行相关测试和必要静态检查，并验证最终可观察结果。不能为了通过测试而降低断言、跳过失败用例或吞掉错误；需求导致预期变化时，说明依据。
4. 检查最终差异，确保每项改动都能关联验收条目或必要依赖，并排除意外的格式、配置、依赖和生成文件变化。
5. 检查失败时，区分本次引入的问题、已有问题和环境限制；修复本次引入的问题，不擅自扩大范围处理无关问题。

最终按以下内容汇报：

- 实际修改及对应验收条目。
- 修改文件和行为变化。
- 实际执行的检查及结果。
- 未执行、未通过或未验证的项目及原因。
- 剩余风险和兼容性影响。

**区分“代码已修改”“检查已通过”和“需求已验证”。只有获得实际验证依据后，才能声称对应需求已完成；局部测试通过不能代替完整验收。**

现在只执行第一阶段。`;

export function buildRequirementPrompt(requirement: string): string {
  if (requirement.length === 0) return REQUIREMENT_PROMPT_TEMPLATE;

  return REQUIREMENT_PROMPT_TEMPLATE.replace(REQUIREMENT_PROMPT_PLACEHOLDER, requirement);
}
